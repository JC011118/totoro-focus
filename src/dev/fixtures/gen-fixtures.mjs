#!/usr/bin/env node
// Generates the dev-preview test sprites (original, CC0, dev only):
//   atlas.svg      4×4 cells of 64×64: exercises row/column/sheet math
//   celebrate.svg  1×6 strip of 96×96: a different frame size, non-looping
// Run: node src/dev/fixtures/gen-fixtures.mjs   (deterministic output)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const C = { body: "#7fb2a3", shade: "#5e9284", hi: "#b5d9ce", line: "#2f4f47", ink: "#20302c", leaf: "#c6d97a", cheek: "#f0a7a0" };

/** A round "moss pebble" critter in a 64×64 cell. */
function critter({ squash = 0, eyes = "open", lean = 0, arm = 0, lift = 0, sparkle = false, cup = false } = {}) {
  const sy = 1 - squash;
  const sx = 1 + squash * 0.6;
  const eye =
    eyes === "open"
      ? `<circle cx="26" cy="38" r="2.2" fill="${C.ink}"/><circle cx="38" cy="38" r="2.2" fill="${C.ink}"/>`
      : eyes === "half"
        ? `<path d="M23.5 38.5h5M35.5 38.5h5" stroke="${C.ink}" stroke-width="1.8" stroke-linecap="round"/>`
        : eyes === "happy"
          ? `<path d="M23.5 39q2.5-3 5 0M35.5 39q2.5-3 5 0" fill="none" stroke="${C.ink}" stroke-width="1.7" stroke-linecap="round"/>`
          : `<path d="M23.5 38q2.5 2.2 5 0M35.5 38q2.5 2.2 5 0" fill="none" stroke="${C.ink}" stroke-width="1.7" stroke-linecap="round"/>`;
  const armPath = arm
    ? `<path d="M48 40q6 ${-6 * arm} 7 ${-12 * arm}" fill="none" stroke="${C.line}" stroke-width="2" stroke-linecap="round"/>`
    : "";
  const spark = sparkle
    ? `<path d="M10 14l1.4 3 3 1.4-3 1.4L10 23l-1.4-3-3-1.4 3-1.4Z M54 10l1 2.2 2.2 1-2.2 1L54 16.4l-1-2.2-2.2-1 2.2-1Z" fill="${C.leaf}" stroke="${C.line}" stroke-width=".8"/>`
    : "";
  const cupSvg = cup
    ? `<g transform="translate(40 44)"><path d="M0 0h10v5a5 5 0 0 1-10 0Z" fill="#f3ead8" stroke="${C.line}" stroke-width="1.2"/><path d="M3 -3q-1-1.5 0-3M7 -3q-1-1.5 0-3" stroke="${C.shade}" stroke-width="1" fill="none" stroke-linecap="round"/></g>`
    : "";
  return `<ellipse cx="32" cy="57" rx="15" ry="2.4" fill="${C.line}" opacity=".18"/>
<g transform="translate(32 56) rotate(${lean}) translate(0 ${-lift}) scale(${sx} ${sy}) translate(-32 -56)">
<path d="M32 18c-1-4 1-8 4-10" fill="none" stroke="${C.line}" stroke-width="2" stroke-linecap="round"/>
<path d="M35.5 9.5c4-5 10-5 13-3-2 5-8 7-13 3Z" fill="${C.leaf}" stroke="${C.line}" stroke-width="1.3" stroke-linejoin="round"/>
<path d="M32 18c12 0 19 9 19 21 0 10-8 17-19 17s-19-7-19-17c0-12 7-21 19-21Z" fill="${C.body}" stroke="${C.line}" stroke-width="2"/>
<ellipse cx="25" cy="28" rx="7" ry="4.5" fill="${C.hi}" opacity=".75"/>
${eye}
<ellipse cx="21" cy="44" rx="3" ry="1.8" fill="${C.cheek}" opacity=".7"/><ellipse cx="43" cy="44" rx="3" ry="1.8" fill="${C.cheek}" opacity=".7"/>
<path d="M29.5 44.5q2.5 2 5 0" fill="none" stroke="${C.ink}" stroke-width="1.5" stroke-linecap="round"/>
${armPath}
</g>${spark}${cupSvg}`;
}

function sheet(cell, cols, rows, frames) {
  const w = cell * cols;
  const h = cell * rows;
  const body = frames
    .map(({ col, row, art }) => {
      const s = cell / 64;
      return `<g transform="translate(${col * cell} ${row * cell}) scale(${s})"><svg width="64" height="64" viewBox="0 0 64 64" overflow="hidden">${art}</svg></g>`;
    })
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">\n<!-- Dev-preview test sprite (original, CC0). Generated by gen-fixtures.mjs. -->\n${body}\n</svg>\n`;
}

const atlas = [
  // row 0: idle (4 frames, breathing)
  ...[0, 0.03, 0.05, 0.03].map((squash, col) => ({ col, row: 0, art: critter({ squash }) })),
  // row 1: focus (cols 0-1, eyes closed), blink (cols 2-3)
  { col: 0, row: 1, art: critter({ eyes: "closed" }) },
  { col: 1, row: 1, art: critter({ eyes: "closed", squash: 0.04 }) },
  { col: 2, row: 1, art: critter({ eyes: "half" }) },
  { col: 3, row: 1, art: critter({ eyes: "closed" }) },
  // row 2: paused (col 0), break (cols 1-3, with a cup)
  { col: 0, row: 2, art: critter({ squash: 0.06 }) },
  { col: 1, row: 2, art: critter({ eyes: "soft", cup: true }) },
  { col: 2, row: 2, art: critter({ eyes: "soft", cup: true, squash: 0.03 }) },
  { col: 3, row: 2, art: critter({ eyes: "closed", cup: true, squash: 0.02 }) },
  // row 3: react / wave (4 frames)
  ...[-6, 6, -4, 0].map((lean, col) => ({ col, row: 3, art: critter({ lean, arm: col === 3 ? 0 : 1, eyes: "happy" }) })),
];

const celebrate = [0, 6, 12, 6, 2, 0].map((lift, col) => ({
  col,
  row: 0,
  art: critter({ lift, eyes: "happy", sparkle: col >= 2, squash: col === 0 ? 0.08 : 0, arm: col >= 2 ? 1 : 0 }),
}));

writeFileSync(join(here, "atlas.svg"), sheet(64, 4, 4, atlas));
writeFileSync(join(here, "celebrate.svg"), sheet(96, 6, 1, celebrate));
console.log("wrote atlas.svg, celebrate.svg");
